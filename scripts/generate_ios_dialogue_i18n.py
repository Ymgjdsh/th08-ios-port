import argparse
import json
from pathlib import Path


def cpp_bytes(value, encoding):
    data = value.encode(encoding)
    return '"' + "".join("\\x{:02X}".format(byte) for byte in data) + '"'


def load_json(path):
    with path.open("r", encoding="utf-8") as stream:
        return json.load(stream)


def lines_for(data, script, key):
    group = data.get(script)
    if group is None:
        return []
    entry = group.get(key)
    if entry is None:
        return []
    return entry.get("lines", [])[:2]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    root = Path(args.root)
    entries = []
    seen = set()

    for ja_path in sorted((root / "ja").glob("msg*.dat.jdiff")):
        zh_path = root / "zh-hans" / ja_path.name
        en_path = root / "en" / ja_path.name
        ja_data = load_json(ja_path)
        zh_data = load_json(zh_path)
        en_data = load_json(en_path)

        message_file = ja_path.name[:-6]
        for script, script_entries in ja_data.items():
            for key, ja_entry in script_entries.items():
                if "_h" in key:
                    continue
                time = int(key.split("_", 1)[0])
                ja_lines = ja_entry.get("lines", [])
                zh_lines = lines_for(zh_data, script, key)
                en_lines = lines_for(en_data, script, key)
                for original_line, ja_line in enumerate(ja_lines):
                    identity = (message_file, int(script), time, ja_line)
                    if identity in seen:
                        raise RuntimeError("duplicate dialogue identity: {!r}".format(identity))
                    seen.add(identity)
                    entries.append((message_file, int(script), time, original_line,
                                    ja_line, zh_lines, en_lines))

    output = []
    output.append("// Generated by generate_ios_dialogue_i18n.py. Do not edit.")
    output.append("#pragma once")
    output.append("")
    output.append("struct IosDialogueTranslationEntry")
    output.append("{")
    output.append("    const char *file;")
    output.append("    int script;")
    output.append("    unsigned short time;")
    output.append("    unsigned char originalLine;")
    output.append("    const char *japaneseCp932;")
    output.append("    const char *chinese[2];")
    output.append("    const char *english[2];")
    output.append("};")
    output.append("")
    output.append("static const IosDialogueTranslationEntry g_iosDialogueTranslations[] = {")
    for message_file, script, time, original_line, ja_line, zh_lines, en_lines in entries:
        zh = list(zh_lines) + [""] * (2 - len(zh_lines))
        en = list(en_lines) + [""] * (2 - len(en_lines))
        output.append("    {%s, %d, %d, %d, %s, {%s, %s}, {%s, %s}}," % (
            cpp_bytes(message_file, "ascii"), script, time, original_line,
            cpp_bytes(ja_line, "cp932"), cpp_bytes(zh[0], "utf-8"),
            cpp_bytes(zh[1], "utf-8"), cpp_bytes(en[0], "utf-8"),
            cpp_bytes(en[1], "utf-8")))
    output.append("};")
    output.append("static const unsigned int g_iosDialogueTranslationCount =")
    output.append("    sizeof(g_iosDialogueTranslations) / sizeof(g_iosDialogueTranslations[0]);")
    output.append("")

    destination = Path(args.output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(output), encoding="ascii")
    print("generated {} dialogue line mappings".format(len(entries)))


if __name__ == "__main__":
    main()
